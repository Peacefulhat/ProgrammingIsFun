//A string is a collection of characters.
//A UTF-8–encoded, growable string.
//It has ownership over the contents of the string, stored in a heap-allocated buffer.
//It is closely related to its borrowed counterpart, the primitive str.
//both String and string slices are UTF-8 encoded.

#![allow(unused)]
#![allow(nonstandard_style)]
use std::string;

fn main() {
    let mut StrFromLiteral = "Hello, Literal".to_string();
    println!("String: {}", StrFromLiteral);

    let mut StrFromLiteral = String::from("hello, literal2");
    println!("String: {}", StrFromLiteral);
    let Hello = String::from("السلام عليكم");
    let Hello2 = String::from("Здравствуйте");
    println!("String: {}", Hello);
    println!("String: {}", Hello2);

    // updating a string
    let mut Str = String::new();
    Str.push('A'); // appending a char
    Str.push_str("Hello"); // Appends a string slice.
                           // this is a bad idea later defined why.
    println!("String: {}", Str.chars().nth(0).unwrap()); // pulling a single chracter from a string at particular index.

    // Concatenating with + or format!
    let S1 = String::from("Hello, ");
    let S2 = String::from("world!");
    //let S3 = S1 + &S2; // note s1 has been moved here and can no longer be used
    //    println!("{}", S1); // error
    let S3 = S1 + &S2; //One way to do so is to use the + operator.
                       // we have to use + in this way(strictly)
                       //The + operator uses the add method,
                       //whose signature looks something like this:
                       //fn add(self, s: &str) -> String{
    println!("String: {S3}");
    //For combining strings in more complicated ways, we can instead use the format! macro:
    let S1 = String::from("tic");
    let S2 = String::from("tac");
    let S3 = String::from("toe");

    let S = format!("{S1}-{S2}-{S3}");
    //The version of the code using format! is much easier to read, and the code generated by the format! macro uses references so that this call doesn’t take ownership of any of its parameters.

    println!("String: {}, {}", S, S3);

    //    Slicing Strings

    //Indexing into a string is often a bad idea because it’s not clear what the return type of the string-indexing operation should be: a byte value, a character, a grapheme cluster, or a string slice. If you really need to use indices to create string slices, therefore, Rust asks you to be more specific.

    //Rather than indexing using [] with a single number, you can use [] with a range to create a string slice containing particular bytes:

    let Hello = "Здравствуйте";

    let S = &Hello[0..4];
    println!("{}", S);

    // the characters method return each characters.
    print!("Characters:\n[");
    for c in "Зд".chars() {
        print!(" {c} ");
    }
    print!("]\n");

    print!("Characters:\n[");
    for c in Hello.chars() {
        print!(" {c} ");
    }
    print!("]\n");
    
 for c in S.chars() {
        print!(" {c} ");
    }
    print!("]\n");
   
    
    //Alternatively, the bytes method returns each raw byte.
    print!("Bytes:\n[");
    for b in "Зд".bytes() {
        print!(" {b} ");
    }
    print!("]");
}
